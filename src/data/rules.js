import { hasWeightManagementCondition } from './sampleData';

// A free-text "Other" answer is stored as "Something else:<what they
// typed>" (see SurveyFields.MultiSelectQuestion) — this strips that prefix
// wherever the raw value would otherwise be shown back to the patient.
function cleanOtherText(value) {
  return value?.startsWith?.('Something else:') ? value.slice('Something else:'.length).trim() : value;
}

// Older saved answers carry a leading emoji ("🌅 Morning"); rule labels
// read better without it. Plain labels pass through unchanged.
function stripEmoji(label) {
  return /^[A-Za-z]/.test(label) ? label : label.split(' ').slice(1).join(' ') || label;
}

// Fixed rules, written by the clinical team — not generated by AI, and
// applied on the spot the moment onboarding is submitted, no waiting and
// no review (see useAppState.submitOnboarding). Each row is independent:
// adding, removing or editing a rule here changes what the app does
// without touching any screen. `test` decides whether the rule fires for
// this patient's answers + plan; `effect` writes whatever it drives into
// the shared `out` accumulator; `label` is the plain-language sentence
// shown to the nurse as "Applied automatically in the app".
export const FIXED_RULES = [
  {
    id: 'equipmentOwned',
    test: (a) => Array.isArray(a.equipment) && a.equipment.length > 0 && !a.equipment.includes('None'),
    effect: (a, p, out) => {
      out.equipmentOwned = equipmentIdsFromLabels(a.equipment);
    },
    label: () => 'Showed exercise options that match the equipment at home',
  },
  {
    id: 'noEquipment',
    test: (a) => Array.isArray(a.equipment) && a.equipment.includes('None'),
    effect: (a, p, out) => {
      out.equipmentOwned = [];
    },
    label: () => "Hid exercises that need equipment the patient doesn't have",
  },
  {
    id: 'approvedActivities',
    test: (a) => Array.isArray(a.activities) && a.activities.length > 0,
    effect: (a, p, out) => {
      out.approvedActivities = a.activities.filter((act) => act !== 'Other' && !act.startsWith('Something else'));
    },
    label: () => "Matched activity suggestions to what the patient enjoys, at the patient's level",
  },
  {
    id: 'readingsTimeReminders',
    test: (a) => Array.isArray(a.readingsTime) && a.readingsTime.length > 0,
    effect: (a, p, out) => {
      out.readingsReminderTime = TIME_FOR_PREFERENCE[a.readingsTime[0]];
    },
    label: (a) => `Set reading reminders for ${a.readingsTime.map(stripEmoji).join(' and ').toLowerCase()}`,
  },
  {
    id: 'exerciseTimeReminder',
    test: (a) => Array.isArray(a.exerciseTime) && a.exerciseTime.length > 0,
    effect: (a, p, out) => {
      out.exerciseReminderTime = TIME_FOR_PREFERENCE[a.exerciseTime[0]];
    },
    label: (a) => `Set exercise reminders for ${a.exerciseTime.map(stripEmoji).join(' and ').toLowerCase()}`,
  },
  {
    id: 'personalReason',
    test: (a) => Array.isArray(a.outcomes) && a.outcomes.length > 0,
    effect: (a, p, out) => {
      out.personalReason = cleanOtherText(a.outcomes[0]);
    },
    label: (a) => `Set "${cleanOtherText(a.outcomes[0])}" as the patient's daily reminder on Home`,
  },
  {
    id: 'barrierTime',
    test: (a) => Array.isArray(a.barriers) && a.barriers.includes('Time'),
    effect: (a, p, out) => {
      out.quickFirst = true;
    },
    label: () => 'Showed Quick 5-minute videos first in Learn',
  },
  {
    id: 'barrierNotSure',
    test: (a) => Array.isArray(a.barriers) && a.barriers.includes('Not sure where to start'),
    effect: (a, p, out) => {
      out.welcomeFirst = true;
    },
    label: () => 'Added a welcome video and a first-week guide to Learn',
  },
  {
    id: 'barrierMotivation',
    test: (a) => Array.isArray(a.barriers) && a.barriers.includes('Motivation'),
    effect: (a, p, out) => {
      out.highlightWins = true;
    },
    label: () => "Highlighted a short daily win and the patient's streak on Home",
  },
  {
    id: 'eatingBarrierEvenings',
    test: (a, p) => hasWeightManagementCondition(p) && Array.isArray(a.eatingBarrier) && a.eatingBarrier.includes('Evening snacks'),
    effect: (a, p, out) => {
      out.eveningCheckIn = true;
    },
    label: () => 'Added an evening check-in reminder',
  },
];

function equipmentIdsFromLabels(labels) {
  const map = {
    'Resistance bands': 'resistance-band',
    'Light dumbbells (1-3 lb)': 'dumbbells',
    'Small ball': 'ball',
    'Step box or sturdy step': 'step-box',
  };
  return labels.map((l) => map[l]).filter(Boolean);
}

/** Runs every fixed rule against this patient's onboarding answers + plan,
 * all at once, with no review step — returns the derived effects (what the
 * app should schedule/show/hide) plus `rulesApplied`, the plain-language
 * log of which rules fired, so the nurse sees "Applied automatically in
 * the app" instead of a silent change. */
export function applyFixedRules(responses, plan) {
  const out = {
    equipmentOwned: [],
    approvedActivities: [],
    personalReason: null,
    quickFirst: false,
    welcomeFirst: false,
    highlightWins: false,
    readingsReminderTime: null,
    exerciseReminderTime: null,
    eveningCheckIn: false,
  };
  const rulesApplied = [];
  for (const rule of FIXED_RULES) {
    if (rule.test(responses, plan)) {
      rule.effect(responses, plan, out);
      rulesApplied.push({ id: rule.id, label: rule.label(responses, plan), appliedAt: new Date().toISOString() });
    }
  }
  return { ...out, rulesApplied };
}

// A default clock time per preferred-time-of-day answer (the readings and
// exercise questions both use the same three options) — reminders are a
// single time-of-day per task today, so picking more than one just uses
// the first as the representative reminder time.
export const TIME_FOR_PREFERENCE = {
  Morning: '08:00',
  Afternoon: '13:00',
  Evening: '18:00',
  // answers saved before the emoji-free options
  '🌅 Morning': '08:00',
  '☀️ Afternoon': '13:00',
  '🌙 Evening': '18:00',
};

// How often the patient's personal reason gets re-asked ("Is this still
// your reason?") — 3 to 4 weeks, per the clinical spec; 21 days is the
// short end of that window.
export const REASON_RECONFIRM_DAYS = 21;

export function shouldReconfirmPersonalReason(personalReason) {
  if (!personalReason?.lastConfirmedAt) return false;
  const days = (Date.now() - new Date(personalReason.lastConfirmedAt).getTime()) / 86400000;
  return days >= REASON_RECONFIRM_DAYS;
}

// The daily motivational reminder (see HomeScreen's ReasonToast) rotates
// through these so it isn't the exact same sentence every day — picked
// deterministically by day-of-year so it's stable for the whole day and
// the same across screens/reloads, not random per render.
export const REASON_MESSAGE_TEMPLATES = [
  (reason) => `Keep it going! Remember, you're working toward: ${reason}.`,
  (reason) => `One day at a time — you're doing this for ${reason}.`,
  (reason) => `You've got this. Stay focused on ${reason}.`,
  (reason) => `Small steps today add up. Keep ${reason} in mind.`,
];

function dayOfYear(date) {
  const start = new Date(date.getFullYear(), 0, 0);
  return Math.floor((date - start) / 86400000);
}

/** Today's rotating motivational message for the personal-reason toast —
 * deterministic per calendar day (see REASON_MESSAGE_TEMPLATES above). */
export function pickDailyReasonMessage(reason, date = new Date()) {
  const idx = dayOfYear(date) % REASON_MESSAGE_TEMPLATES.length;
  return REASON_MESSAGE_TEMPLATES[idx](reason);
}
